// Builds the theme's bilingual demo data and English interface translations:
//   theme/toplist-khanh-hoa/demo/content.json        — imported by Tools → Dữ liệu mẫu / `wp tkh demo-import`
//   theme/toplist-khanh-hoa/languages/en_US.l10n.php — WordPress 6.5+ PHP translation file
// Fails when a post, page or interface string has no English version.
import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { categories, regions, tags } from '../content/taxonomy.js';
import pagesVi from '../content/pages.js';
import duLich from '../content/posts-du-lich.js';
import amThuc from '../content/posts-am-thuc.js';
import luuTru from '../content/posts-luu-tru.js';
import giaiTriCafe from '../content/posts-giai-tri-cafe.js';
import enDuLich from '../content/en/posts-du-lich.js';
import enAmThuc from '../content/en/posts-am-thuc.js';
import enRest from '../content/en/posts-luu-tru-giai-tri-cafe.js';
import enPages from '../content/en/pages.js';
import { strings, plurals } from '../content/theme-strings-en.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const themeDir = path.join(root, 'theme', 'toplist-khanh-hoa');
const postsVi = [...duLich, ...amThuc, ...luuTru, ...giaiTriCafe];
const postsEn = { ...enDuLich, ...enAmThuc, ...enRest };
const errors = [];

const term = (t) => ({ key: t.slug, vi: { slug: t.slug, name: t.name, description: t.description ?? '' }, en: t.en });

function buildPosts() {
  const keys = new Set(['rating', 'review_count', 'price_level']);
  return postsVi.map((p) => {
    const en = postsEn[p.slug];
    if (!en) {
      errors.push(`post ${p.slug}: missing English version`);
      return null;
    }
    const shared = Object.fromEntries(Object.entries(p.meta).filter(([k]) => keys.has(k)));
    const local = (meta, placeName) => ({ ...Object.fromEntries(Object.entries(meta).filter(([k]) => !keys.has(k))), place_name: placeName });
    return {
      key: p.slug,
      date: p.date,
      category: p.category,
      region: p.region,
      tags: p.tags,
      image: p.image,
      meta: shared,
      vi: { slug: p.slug, title: p.title, excerpt: p.excerpt, content: p.content.trim(), meta: local(p.meta, en.placeNameVi) },
      en: { slug: en.slug, title: en.title, excerpt: en.excerpt, content: en.content.trim(), meta: local({ ...p.meta, ...en.meta, address: p.meta.address }, en.placeName) },
    };
  }).filter(Boolean);
}

function buildPages() {
  return pagesVi.map((pg) => {
    const en = enPages[pg.slug];
    if (!en) errors.push(`page ${pg.slug}: missing English version`);
    return {
      key: pg.slug,
      template: pg.slug === 'yeu-thich' ? 'page-templates/favorites.php' : '',
      vi: { slug: pg.slug, title: pg.title, content: pg.content.trim() },
      en: en ? { slug: en.slug, title: en.title, content: en.content.trim() } : null,
    };
  });
}

// --- Interface translations -------------------------------------------------------------

async function phpFiles(dir) {
  const out = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const p = path.join(dir, entry.name);
    if (entry.isDirectory()) out.push(...(await phpFiles(p)));
    else if (entry.name.endsWith('.php')) out.push(p);
  }
  return out;
}

async function usedStrings() {
  const single = new Set();
  const plural = new Map();
  const unescape = (s) => s.replace(/\\(['\\])/g, '$1');
  for (const file of await phpFiles(themeDir)) {
    const src = await readFile(file, 'utf8');
    for (const m of src.matchAll(/\b(?:__|_e|esc_html__|esc_html_e|esc_attr__|esc_attr_e)\(\s*'((?:[^'\\]|\\.)*)'\s*,\s*'toplist-khanh-hoa'/g)) single.add(unescape(m[1]));
    for (const m of src.matchAll(/\b_n\(\s*'((?:[^'\\]|\\.)*)'\s*,\s*'((?:[^'\\]|\\.)*)'\s*,[^;]*?'toplist-khanh-hoa'/g)) plural.set(unescape(m[1]), unescape(m[2]));
  }
  return { single, plural };
}

const phpString = (s) => s.split('\0').map((part) => `'${part.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`).join(' . "\\0" . ');

async function buildTranslations() {
  const { single, plural } = await usedStrings();
  for (const s of single) if (!(s in strings)) errors.push(`missing English string: ${s}`);
  for (const s of plural.keys()) if (!(s in plurals)) errors.push(`missing English plural: ${s}`);

  const lines = [];
  for (const s of [...single].sort()) if (s in strings) lines.push(`\t\t${phpString(s)} => ${phpString(strings[s])},`);
  for (const [singular, pluralForm] of plural) {
    if (plurals[singular]) lines.push(`\t\t${phpString(`${singular}\0${pluralForm}`)} => ${phpString(plurals[singular].join('\0'))},`);
  }
  return `<?php
// Generated by scripts/build-content.js from content/theme-strings-en.js — do not edit by hand.
return array(
\t'domain'       => 'toplist-khanh-hoa',
\t'plural-forms' => 'nplurals=2; plural=(n != 1);',
\t'language'     => 'en_US',
\t'messages'     => array(
${lines.join('\n')}
\t),
);
`;
}

const data = {
  generated: new Date().toISOString(),
  categories: categories.map(term),
  regions: regions.map(term),
  tags: tags.map(term),
  posts: buildPosts(),
  pages: buildPages(),
};
const l10n = await buildTranslations();

if (errors.length) {
  console.error(`Content build failed:\n- ${errors.join('\n- ')}`);
  process.exit(1);
}

await mkdir(path.join(themeDir, 'demo'), { recursive: true });
await mkdir(path.join(themeDir, 'languages'), { recursive: true });
await writeFile(path.join(themeDir, 'demo', 'content.json'), JSON.stringify(data, null, 1), 'utf8');
await writeFile(path.join(themeDir, 'languages', 'en_US.l10n.php'), l10n, 'utf8');
console.log(`Demo data: ${data.posts.length} posts × 2 languages, ${data.pages.length} pages × 2; translations: ${Object.keys(strings).length} strings`);
